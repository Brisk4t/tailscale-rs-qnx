#!/bin/bash
# Set up everything this repo builds against:
#
#   1. Crate forks: each patches/<crate>-<version>.patch -> <repo>/build/patched-crates/<crate>-<version>/
#      (pristine crates.io source committed, QNX patch applied on top, uncommitted).
#   2. tailscale-rs: cloned at $TAILSCALE_RS_REF into <repo>/build/tailscale-rs (git-ignored), with
#      patches/tailscale-rs/*.patch applied in order (uncommitted, on a local branch `$TAILSCALE_RS_REF-qnx`).
#      The patches are this port's changes to tailscale-rs; upstream has no QNX branch.
#   3. tailscale-rs's local .cargo/config.toml: QNX target settings plus a [patch.crates-io]
#      entry for every fork from step 1, with absolute paths. Excluded from git.
#
# Usage: scripts/setup.sh
# Env:   TAILSCALE_RS_REF  (default: v0.7.1)
#
# Everything goes in <repo>/build/ (git-ignored), where the workspace's path dependencies expect it.
# Delete build/ and rerun to start over.
#
# Safe to rerun: existing forks and checkouts are left alone, an already-applied patch is detected,
# and a cargo config this script didn't write is never overwritten.
set -euo pipefail

repo=$(cd "$(dirname "$0")/.." && pwd)
crates=$repo/build/patched-crates
# The workspace's path dependencies (apps/ts-forward, smoke/netmon-smoke) expect it here.
tsrs=$repo/build/tailscale-rs
tsrs_ref=${TAILSCALE_RS_REF:-v0.7.1}
mkdir -p "$crates"
crates=$(cd "$crates" && pwd)

# --- 1. crate forks -------------------------------------------------------------------------
echo "== crate forks -> $crates"
for patch in "$repo"/patches/*.patch; do
    crate_ver=$(basename "$patch" .patch)    # e.g. mio-1.2.4
    name=${crate_ver%-*}
    dir=$crates/$crate_ver
    if [ -e "$dir" ]; then
        echo "skip  $crate_ver (already at $dir)"
        continue
    fi
    tmp=$(mktemp -d)
    curl -fsSL "https://static.crates.io/crates/$name/$crate_ver.crate" | tar -xz -C "$tmp"
    mv "$tmp/$crate_ver" "$dir"
    rmdir "$tmp"
    git -C "$dir" init -q
    git -C "$dir" add -A
    git -C "$dir" -c user.name=qnx-port -c user.email=qnx-port@localhost \
        commit -qm "Pristine $crate_ver from crates.io"
    git -C "$dir" apply "$patch"
    echo "ready $crate_ver ($(git -C "$dir" diff --shortstat))"
done

# --- 2. tailscale-rs checkout + QNX patch ----------------------------------------------------
if [ ! -e "$tsrs" ]; then
    mkdir -p "$(dirname "$tsrs")"
    git clone -q https://github.com/tailscale/tailscale-rs.git "$tsrs"
    git -C "$tsrs" checkout -q -b "$tsrs_ref-qnx" "$tsrs_ref"
    echo "cloned tailscale-rs at $tsrs_ref (local branch $tsrs_ref-qnx)"
fi
tsrs=$(cd "$tsrs" && pwd)
echo "== tailscale-rs -> $tsrs"
for patch in "$repo"/patches/tailscale-rs/*.patch; do
    p=$(basename "$patch")
    if git -C "$tsrs" apply --reverse --check "$patch" 2>/dev/null; then
        echo "skip  $p (already applied)"
    elif git -C "$tsrs" apply --check "$patch" 2>/dev/null; then
        git -C "$tsrs" apply "$patch"
        echo "ready $p ($(grep -c '^diff --git' "$patch") files)"
    else
        echo "error: $p neither applies to nor is applied in $tsrs." >&2
        echo "       Is it at $tsrs_ref? Local changes in the way? Check with: git -C $tsrs status" >&2
        exit 1
    fi
done

# --- 3. tailscale-rs local cargo config ------------------------------------------------------
marker="# Generated by tailscale-QNX scripts/setup.sh"
config=$tsrs/.cargo/config.toml
new=$(mktemp)
{
    echo "$marker; rerun it to regenerate. Not for upstream (excluded via .git/info/exclude)."
    echo "# Host builds are unaffected: everything below only applies with --target x86_64-pc-qnx or aarch64-unknown-qnx."
    cat <<EOF

[target.x86_64-pc-qnx]
linker = "qcc"
runner = "$repo/scripts/qnx-run.sh"

[target.aarch64-unknown-qnx]
linker = "qcc"

[unstable]
build-std = ["std", "panic_abort"]

[env]
CC_x86_64_pc_qnx = "qcc"
CFLAGS_x86_64_pc_qnx = "-Vgcc_ntox86_64"
CXX_x86_64_pc_qnx = "q++"
CXXFLAGS_x86_64_pc_qnx = "-Vgcc_ntox86_64_cxx"
AR_x86_64_pc_qnx = "ntox86_64-ar"
CC_aarch64_unknown_qnx = "qcc"
CFLAGS_aarch64_unknown_qnx = "-Vgcc_ntoaarch64le"
CXX_aarch64_unknown_qnx = "q++"
CXXFLAGS_aarch64_unknown_qnx = "-Vgcc_ntoaarch64le_cxx"
AR_aarch64_unknown_qnx = "ntoaarch64-ar"

[patch.crates-io]
EOF
    # One entry per fork. A crate forked at several versions (getrandom) needs a distinct key per
    # version: name + major + minor digits, e.g. getrandom-0.2.17 -> getrandom02.
    for patch in "$repo"/patches/*.patch; do
        crate_ver=$(basename "$patch" .patch)
        name=${crate_ver%-*}
        ver=${crate_ver##*-}
        if [ "$(ls "$repo"/patches/"$name"-[0-9]*.patch | wc -l)" -gt 1 ]; then
            major_minor=$(echo "$ver" | cut -d. -f1,2 | tr -d .)
            echo "$name$major_minor = { package = \"$name\", path = \"$crates/$crate_ver\" }"
        else
            echo "$name = { path = \"$crates/$crate_ver\" }"
        fi
    done
} > "$new"

mkdir -p "$tsrs/.cargo"
if [ ! -e "$config" ]; then
    mv "$new" "$config"
    echo "wrote $config"
elif cmp -s "$new" "$config"; then
    rm "$new"
    echo "skip  $config (up to date)"
elif head -1 "$config" | grep -qF "$marker"; then
    mv "$new" "$config"
    echo "updated $config"
else
    mv "$new" "$config.setup-new"
    echo "warning: $config wasn't written by this script, so it's left alone." >&2
    echo "         The generated version is in $config.setup-new; compare and replace it yourself." >&2
fi
# Ask git for the exclude file: in a worktree, .git is a file, not a directory.
exclude=$(git -C "$tsrs" rev-parse --path-format=absolute --git-path info/exclude)
mkdir -p "$(dirname "$exclude")"
grep -qxF '/.cargo/' "$exclude" 2>/dev/null || echo '/.cargo/' >> "$exclude"

echo "== done. Next: source ~/qnx800/qnxsdp-env.sh, then build (README, Getting Started step 3)."
